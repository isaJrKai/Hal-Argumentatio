import { LandingPageConfig } from './types';

/**
 * Generates production-ready React / Next.js TSX code for the configured landing page.
 */
export function generateLandingPageTsx(config: LandingPageConfig): string {
  const {
    id,
    businessName,
    city,
    phone,
    licenseNumber,
    branding,
    sectionOrder,
    sections,
    seo
  } = config;

  const componentName = businessName.replace(/[^a-zA-Z0-9]/g, '') || 'ContractorLandingPage';

  return `// Generated by HAL Landing Page Studio
// Framework: React / Next.js (Tailwind CSS)
'use client';

import React, { useState } from 'react';

export default function ${componentName}() {
  const [formData, setFormData] = useState({ name: '', phone: '', details: '' });
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [submitted, setSubmitted] = useState(false);
  const [submitError, setSubmitError] = useState<string | null>(null);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!formData.name || !formData.phone || !formData.details) return;

    setIsSubmitting(true);
    try {
      const res = await fetch('/api/public/landing-leads', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contractorId: '${config.contractorId || ''}',
          landingPageId: '${id}',
          name: formData.name,
          phone: formData.phone,
          serviceDetails: formData.details,
          city: '${city}'
        })
      });
      if (!res.ok) throw new Error('The request could not be sent. Please try again or contact the business directly.');
      setSubmitted(true);
      setSubmitError(null);
    } catch (err) {
      setSubmitError(err instanceof Error ? err.message : 'The request could not be sent. Please try again.');
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <div className="min-h-screen bg-slate-950 text-slate-100 font-sans antialiased selection:bg-amber-500 selection:text-slate-950 pb-16 sm:pb-0">
      ${sections.announcement_bar?.active ? `
      {/* Top Announcement Bar */}
      <div className="bg-amber-500 text-slate-950 px-4 py-2 text-center text-xs font-bold uppercase tracking-wider flex items-center justify-center gap-2">
        <span className="px-1.5 py-0.5 rounded bg-slate-950 text-amber-400 text-[10px] font-black mr-1">
          ${sections.announcement_bar.urgencyBadge}
        </span>
        <span>${sections.announcement_bar.text}</span>
      </div>` : ''}

      ${sections.header?.active ? `
      {/* Sticky Header */}
      <header className="border-b border-slate-800/80 bg-slate-950/80 backdrop-blur-md sticky top-0 z-40">
        <div className="max-w-6xl mx-auto px-4 sm:px-6 py-4 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 rounded-xl bg-gradient-to-tr from-sky-500 to-amber-500 flex items-center justify-center font-black text-slate-950 text-base shadow-md">
              ${(branding.logoText || businessName).slice(0, 2).toUpperCase()}
            </div>
            <div>
              <span className="font-extrabold text-base sm:text-lg tracking-tight text-white block leading-tight">
                ${branding.logoText || businessName}
              </span>
              <span className="text-[11px] text-slate-400 block">${licenseNumber}</span>
            </div>
          </div>
          <div className="flex items-center gap-3">
            <div className="hidden sm:block text-right">
              <div className="text-[10px] uppercase font-bold text-amber-400 tracking-wider">Contact the Business</div>
              <div className="text-sm font-black text-white">${phone || 'Use the quote form'}</div>
            </div>
            <a
              href="${phone.replace(/[^0-9+]/g, '') ? 'tel:' + phone.replace(/[^0-9+]/g, '') : '#lead-form'}"
              className="bg-amber-500 hover:bg-amber-400 text-slate-950 font-extrabold px-4 py-2.5 rounded-xl text-xs sm:text-sm transition flex items-center gap-2 shadow-lg"
            >
              <span>📞</span>
              <span className="hidden sm:inline">${sections.header.ctaText}</span>
              <span className="sm:hidden">${phone ? 'Call Now' : 'Request a Quote'}</span>
            </a>
          </div>
        </div>
      </header>` : ''}

      <main className="space-y-12">
        ${sections.hero?.active ? `
        {/* Hero Section */}
        <section className="relative overflow-hidden pt-8 pb-12 px-4 sm:px-6">
          <div className="max-w-6xl mx-auto grid grid-cols-1 lg:grid-cols-12 gap-8 items-center">
            <div className="lg:col-span-7 space-y-6 text-center lg:text-left">
              <div className="inline-flex items-center gap-2 px-3 py-1.5 rounded-full bg-slate-800/90 border border-slate-700 text-sky-400 text-xs font-semibold">
                <span className="w-2 h-2 rounded-full bg-emerald-400 animate-pulse"></span>
                <span>${sections.hero.badgeText}</span>
              </div>
              <h1 className="text-3xl sm:text-5xl font-black text-white tracking-tight leading-tight">
                ${sections.hero.headline}
              </h1>
              <p className="text-slate-300 text-sm sm:text-base leading-relaxed max-w-xl mx-auto lg:mx-0">
                ${sections.hero.subheadline}
              </p>
            </div>

            {/* Lead Form */}
            <div id="lead-form" className="lg:col-span-5">
              <div className="p-6 sm:p-7 rounded-2xl bg-slate-900/90 border border-slate-700/80 shadow-2xl relative backdrop-blur-md">
                <div className="absolute -top-3 right-6 bg-emerald-500 text-slate-950 font-black text-[10px] uppercase px-3 py-1 rounded-full shadow-md">
                  Request a Quote
                </div>
                <h3 className="text-xl font-bold text-white mb-1">
                  ${sections.lead_form?.title || 'Request Priority Dispatch'}
                </h3>
                <p className="text-xs text-slate-400 mb-5">
                  ${sections.lead_form?.subtitle || 'Enter your details below for instant contact.'}
                </p>

                {submitted ? (
                  <div className="p-4 rounded-xl bg-emerald-950/80 border border-emerald-500 text-center space-y-2">
                    <div className="text-emerald-400 text-xl font-bold">✓ Request Confirmed</div>
                    <p className="text-xs text-slate-200">
                      The business has received your request and can follow up using the contact details provided.
                    </p>
                  </div>
                ) : (
                  <>
                    {submitError && <p role="alert" className="text-sm text-rose-400 mb-3">{submitError}</p>}
                    <form onSubmit={handleSubmit} className="space-y-3.5">
                    <div>
                      <label className="block text-[11px] font-semibold text-slate-300 mb-1">Full Name *</label>
                      <input
                        type="text"
                        required
                        value={formData.name}
                        onChange={(e) => setFormData({ ...formData, name: e.target.value })}
                        placeholder="e.g. Sarah Jenkins"
                        className="w-full px-3.5 py-2.5 rounded-xl bg-slate-950 border border-slate-700 text-white placeholder-slate-500 text-sm focus:outline-none focus:border-amber-400"
                      />
                    </div>
                    <div>
                      <label className="block text-[11px] font-semibold text-slate-300 mb-1">Phone Number *</label>
                      <input
                        type="tel"
                        required
                        value={formData.phone}
                        onChange={(e) => setFormData({ ...formData, phone: e.target.value })}
                        placeholder="Enter phone number"
                        className="w-full px-3.5 py-2.5 rounded-xl bg-slate-950 border border-slate-700 text-white placeholder-slate-500 text-sm focus:outline-none focus:border-amber-400"
                      />
                    </div>
                    <div>
                      <label className="block text-[11px] font-semibold text-slate-300 mb-1">Issue / Service *</label>
                      <textarea
                        rows={2}
                        required
                        value={formData.details}
                        onChange={(e) => setFormData({ ...formData, details: e.target.value })}
                        placeholder="Describe the issue..."
                        className="w-full px-3.5 py-2.5 rounded-xl bg-slate-950 border border-slate-700 text-white placeholder-slate-500 text-sm focus:outline-none focus:border-amber-400"
                      />
                    </div>
                    <button
                      type="submit"
                      disabled={isSubmitting}
                      className="w-full py-3.5 px-4 rounded-xl bg-amber-500 hover:bg-amber-400 text-slate-950 font-black text-sm transition shadow-lg cursor-pointer disabled:opacity-50"
                    >
                      {isSubmitting ? 'Sending Request...' : '${sections.lead_form?.buttonText || '⚡ Dispatch Technician Now'}'}
                    </button>
                    </form>
                  </>
                )}
              </div>
            </div>
          </div>
        </section>` : ''}

        ${sections.bento_features?.active && sections.bento_features.items?.length > 0 ? `
        {/* Bento Grid Features */}
        <section className="max-w-6xl mx-auto px-4 sm:px-6 py-8">
          <div className="text-center max-w-2xl mx-auto mb-8 space-y-2">
            ${sections.bento_features.badge ? `<span className="inline-block px-3 py-1 rounded-full bg-amber-500/10 border border-amber-500/30 text-amber-400 text-[11px] font-bold tracking-wider uppercase">${sections.bento_features.badge}</span>` : ''}
            <h2 className="text-2xl sm:text-3xl font-black text-white">${sections.bento_features.title}</h2>
            <p className="text-xs sm:text-sm text-slate-400">${sections.bento_features.subtitle}</p>
          </div>
          <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
            ${sections.bento_features.items.map(item => `
            <div className="${item.colSpan === '2' ? 'md:col-span-2' : item.colSpan === '3' ? 'md:col-span-3' : 'md:col-span-1'} p-6 rounded-2xl bg-slate-900/70 border border-slate-800 flex flex-col justify-between space-y-4">
              <div className="space-y-2">
                <div className="flex items-center justify-between">
                  ${item.tag ? `<span className="text-[10px] uppercase font-bold tracking-wider px-2 py-0.5 rounded bg-amber-500/10 text-amber-400 border border-amber-500/20">${item.tag}</span>` : '<span></span>'}
                  ${item.icon ? `<span className="text-xl">${item.icon}</span>` : ''}
                </div>
                <h3 className="text-lg font-bold text-white tracking-tight">${item.title}</h3>
                <p className="text-xs text-slate-400 leading-relaxed">${item.subtitle}</p>
              </div>
              ${item.value ? `
              <div className="pt-3 border-t border-slate-800/80 flex items-baseline gap-2">
                <span className="text-2xl font-black text-white">${item.value}</span>
                <span className="text-[11px] text-slate-500">Verified Metric</span>
              </div>` : ''}
            </div>`).join('\n')}
          </div>
        </section>` : ''}

        ${sections.pricing_packages?.active && sections.pricing_packages.items?.length > 0 ? `
        {/* Pricing Packages */}
        <section className="max-w-6xl mx-auto px-4 sm:px-6 py-8">
          <div className="text-center max-w-2xl mx-auto mb-8 space-y-2">
            ${sections.pricing_packages.badge ? `<span className="inline-block px-3 py-1 rounded-full bg-emerald-500/10 border border-emerald-500/30 text-emerald-400 text-[11px] font-bold tracking-wider uppercase">${sections.pricing_packages.badge}</span>` : ''}
            <h2 className="text-2xl sm:text-3xl font-black text-white">${sections.pricing_packages.title}</h2>
            <p className="text-xs sm:text-sm text-slate-400">${sections.pricing_packages.subtitle}</p>
          </div>
          <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
            ${sections.pricing_packages.items.map(tier => `
            <div className="p-6 rounded-2xl flex flex-col justify-between ${tier.popular ? 'bg-gradient-to-b from-slate-900 to-slate-950 border-2 border-amber-500 shadow-xl' : 'bg-slate-900/60 border border-slate-800'}">
              <div>
                <h3 className="text-lg font-black text-white">${tier.name}</h3>
                <p className="text-xs text-slate-400 mt-1 mb-4">${tier.tagline}</p>
                <div className="flex items-baseline gap-1 my-3">
                  <span className="text-3xl font-black text-white tracking-tight">${tier.price}</span>
                  ${tier.period ? `<span className="text-xs text-slate-400 font-medium">${tier.period}</span>` : ''}
                </div>
                <div className="space-y-2 pt-3 border-t border-slate-800/80 my-4 text-xs">
                  ${(tier.features || []).map(f => `
                  <div className="flex items-start gap-2 text-slate-300">
                    <span className="text-amber-400 font-bold">✓</span>
                    <span>${f}</span>
                  </div>`).join('\n')}
                </div>
              </div>
              <div className="pt-2">
                <a
                  href="#lead-form"
                  className="w-full py-3 px-4 rounded-xl text-center font-bold text-xs transition block ${tier.popular ? 'bg-amber-500 hover:bg-amber-400 text-slate-950' : 'bg-slate-800 hover:bg-slate-700 text-white border border-slate-700'}"
                >
                  ${tier.ctaText || 'Select Package'}
                </a>
              </div>
            </div>`).join('\n')}
          </div>
        </section>` : ''}
      </main>

      {/* Footer */}
      <footer className="border-t border-slate-800/80 py-8 px-4 sm:px-6 mt-16 bg-slate-950 text-center space-y-2 text-xs text-slate-500">
        <p className="font-medium text-slate-400">${businessName} • ${licenseNumber}</p>
        <p>${city} • 24/7 Dispatch Phone: <span className="text-amber-400 font-bold">${phone}</span></p>
      </footer>
    </div>
  );
}
`;
}
